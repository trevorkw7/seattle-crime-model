const N_ROWS = Math.ceil(((BBOX[3] - BBOX[1]) * M_PER_DEG_LAT) / CELL_M);
const N_COLS = Math.ceil(((BBOX[2] - BBOX[0]) * M_PER_DEG_LON) / CELL_M);

const cells = [];
for (let row = 0; row < N_ROWS; row++) {
  for (let col = 0; col < N_COLS; col++) {
    const w = BBOX[0] + col * D_LON;
    const s = BBOX[1] + row * D_LAT;
    const e = w + D_LON;
    const n = s + D_LAT;
    const center = [w + D_LON / 2, s + D_LAT / 2];
    const corners = [[w, s], [e, s], [e, n], [w, n]];
    const inCity = pointInPolygon(center, CITY);
    const touches = inCity || corners.some((c) => pointInPolygon(c, CITY));
    if (!touches) continue;
    let best = null;
    let bestD = Infinity;
    for (const [name, lon, lat] of NEIGHBORHOODS) {
      const d = kmBetween(center[0], center[1], lon, lat);
      if (d < bestD) {
        bestD = d;
        best = name;
      }
    }
    cells.push({
      id: `r${row}_c${col}`,
      row,
      col,
      center,
      ring: [...corners, corners[0]].map(([x, y]) => [dec(x, 6), dec(y, 6)]),
      inCity,
      neighborhood: inCity && bestD < 2.2 ? best : null,
    });
  }
}

// Static spatial intensity per category (relative weights, later scaled to CITY_RATE).
function spatialWeight(cell, catIdx) {
  const [lon, lat] = cell.center;
  let v = 0.16;
  for (const b of BUMPS) {
    const d = kmBetween(lon, lat, b[0], b[1]);
    v += b[3 + catIdx] * Math.exp(-(d * d) / (2 * b[2] * b[2]));
  }
  for (const c of CORRIDORS) {
    const d = kmToSegment(lon, lat, c);
    v += c[5 + catIdx] * Math.exp(-(d * d) / (2 * c[4] * c[4]));
  }
  // gentle deterministic texture so neighbouring cells are not identical
  const tex = 1 + 0.18 * Math.sin(lon * 310 + lat * 170 + catIdx) * Math.cos(lat * 260 - lon * 90);
  return v * tex * (cell.inCity ? 1 : 0.35);
}

const CAT_INDEX = { property: 0, violent: 1, all_located: 2 };
const baseRate = {}; // category -> Float64Array of mean reports/hour per cell
for (const cat of CATEGORIES) {
  const w = cells.map((c) => spatialWeight(c, CAT_INDEX[cat.id]));
  const sum = w.reduce((a, b) => a + b, 0);
  baseRate[cat.id] = Float64Array.from(w, (x) => (x / sum) * CITY_RATE[cat.id]);
}

// Hour-of-week profile, local time, Monday 00:00 first; mean = 1.
function weeklyProfile(cat) {
  const prof = [];
  for (let how = 0; how < 168; how++) {
    const day = Math.floor(how / 24); // 0 = Monday
    const h = how % 24;
    const weekend = day >= 5;
    let v;
    if (cat === 'violent') {
      v = 0.55 + 0.45 * Math.cos(((h - 21) / 24) * 2 * Math.PI) + (day >= 4 && (h >= 21 || h <= 2) ? 0.5 : 0);
    } else {
      // property & all: reports peak late morning / afternoon when losses are discovered
      v = 0.62 + 0.5 * Math.cos(((h - 13) / 24) * 2 * Math.PI) + 0.12 * Math.cos(((h - 9) / 12) * 2 * Math.PI);
      if (weekend) v *= 0.9;
    }
    prof.push(Math.max(0.12, v));
  }
  const mean = prof.reduce((a, b) => a + b, 0) / 168;
  return prof.map((x) => x / mean);
}
const PROFILE = Object.fromEntries(CATEGORIES.map((c) => [c.id, weeklyProfile(c.id)]));
function howOf(ms) {
  const local = new Date(ms + TZ_OFFSET_H * HOUR);
  const dow = (local.getUTCDay() + 6) % 7; // Monday = 0
  return dow * 24 + local.getUTCHours();
}

// Slowly moving, spatially smooth anomaly field (multiplicative, ~0.55x – 2x): a broad
// wave plus a few drifting "recent activity" blobs, so relative-risk maps show
// coherent areas above/below the seasonal baseline rather than speckle.
const BLOBS = [
  // lon, lat, sigma_km, amplitude, drift lon/day, drift lat/day
  [-122.33, 47.61, 0.9, 0.75, 0.0012, -0.0009],
  [-122.3, 47.55, 1.1, 0.6, -0.0008, 0.0011],
  [-122.36, 47.69, 1.0, 0.55, 0.0009, 0.0006],
  [-122.38, 47.56, 0.8, -0.5, 0.0005, 0.0012],
  [-122.3, 47.68, 1.2, -0.45, -0.0011, -0.0005],
];
function anomaly(cell, t, cat) {
  const [lon, lat] = cell.center;
  const tt = (t - ANCHOR) / DAY;
  const c = CAT_INDEX[cat];
  let a = 0.16 * Math.sin(lon * 55 + tt * 0.7 + c) * Math.cos(lat * 70 - tt * 0.5 + c * 0.7);
  for (const [bx, by, s, amp, dx, dy] of BLOBS) {
    const d = kmBetween(lon, lat, bx + dx * tt + c * 0.004, by + dy * tt - c * 0.003);
    a += amp * (c === 1 ? 1.2 : 1) * Math.exp(-(d * d) / (2 * s * s));
  }
  return Math.exp(a);
}

// Expected count for a window [t0, t0 + h) under a given model.
function expectedFor(model, cat, cellIdx, t0, h) {
  const cell = cells[cellIdx];
  let mu = 0;
  let base = 0;
  for (let k = 0; k < h; k++) {
    const t = t0 + k * HOUR;
    const seasonal = baseRate[cat][cellIdx] * PROFILE[cat][howOf(t)];
    base += seasonal;
    if (model === 'lgbm') mu += seasonal * anomaly(cell, t, cat);
    else mu += seasonal * (0.85 + 0.15 * anomaly(cell, t - 7 * DAY, cat)); // KDE: smoother, lagged
  }
  return { mu, base };
}

