// history/<category>.json
const HIST_END = ANCHOR - 26 * HOUR;
for (const c of CATEGORIES) {
  const r = rng(`history|${c.id}`);
  const periods = {};
  for (const [key, days] of [['last_7d', 7], ['last_30d', 30], ['last_365d', 365]]) {
    const out = {};
    cells.forEach((cell, i) => {
      const mu = baseRate[c.id][i] * 24 * days * Math.exp(0.25 * normal(r));
      const n = poisson(r, mu);
      if (n >= MIN_COUNT) out[cell.id] = n;
      else if (n > 0) out[cell.id] = null; // suppressed (1 .. min_count-1)
    });
    periods[key] = { start: iso(HIST_END - days * DAY), end: iso(HIST_END), cells: out };
  }
  write(`history/${c.id}.json`, {
    provenance: PROVENANCE,
    category: c.id,
    min_count: MIN_COUNT,
    periods,
    hour_of_week_citywide: PROFILE[c.id].map((x) => dec(x * CITY_RATE[c.id], 3)),
  });
}

// evaluation/summary.json
{
  const r = rng('evaluation');
  const jitter = (s) => s * normal(r);
  const BASE_C10 = {
    property: { 1: 0.27, 3: 0.3, 6: 0.33, 24: 0.38 },
    violent: { 1: 0.33, 3: 0.36, 6: 0.39, 24: 0.44 },
    all_located: { 1: 0.29, 3: 0.32, 6: 0.35, 24: 0.4 },
  };
  const MODEL_DELTA = { lgbm: 0, hotspot_kde: -0.035 };
  const P_MEAN = { 1: 0.006, 3: 0.017, 6: 0.032, 24: 0.11 };
  const catScale = { property: 1, violent: 0.16, all_located: 1.6 };

  function metricRow(model, cat, h, shift = 0) {
    const c10 = BASE_C10[cat][h] + MODEL_DELTA[model] + shift + jitter(0.006);
    const c5 = c10 * (0.6 + jitter(0.01));
    const c20 = Math.min(0.95, c10 * (1.55 + jitter(0.02)));
    const p = Math.min(0.6, P_MEAN[h] * catScale[cat]);
    const brier = p * (1 - p) * (model === 'lgbm' ? 0.93 : 0.97);
    const ci = (v, w) => [dec(v - w, 3), dec(v + w, 3)];
    return {
      model_id: model,
      category: cat,
      horizon_h: h,
      capture_5: dec(c5, 3),
      capture_10: dec(c10, 3),
      capture_20: dec(c20, 3),
      pai_10: dec(c10 / 0.1, 2),
      lift_vs_seasonal_10: dec(model === 'lgbm' ? 1.05 + 0.02 * Math.log2(h + 1) + jitter(0.01) : 0.99 + jitter(0.01), 3),
      poisson_deviance: dec(p * (model === 'lgbm' ? 1.9 : 2.05) * (1 + jitter(0.02)), 4),
      nll: dec(-(p * Math.log(p) + (1 - p) * Math.log(1 - p)) * (model === 'lgbm' ? 0.96 : 1.0), 4),
      mae: dec(p * 1.8 * (model === 'lgbm' ? 0.95 : 1), 4),
      rmse: dec(Math.sqrt(p) * (model === 'lgbm' ? 0.97 : 1), 4),
      brier: dec(brier, 5),
      ece: dec(Math.abs(p * (model === 'lgbm' ? 0.04 : 0.12) + jitter(0.0003)), 5),
      ci: {
        capture_5: ci(c5, 0.012 / Math.sqrt(h / 6 + 0.5)),
        capture_10: ci(c10, 0.011 / Math.sqrt(h / 6 + 0.5)),
        capture_20: ci(c20, 0.01 / Math.sqrt(h / 6 + 0.5)),
      },
    };
  }

  const backtestRows = [];
  const prospectiveRows = [];
  const timeseries = [];
  const ablations = [];
  const calibration = [];
  const byPrecinct = [];
  const byMonth = [];
  const PROSPECTIVE_START = ANCHOR - 56 * DAY;
  const LIVE_DAYS = 14;
  const LIVE_START = ANCHOR - LIVE_DAYS * DAY;
  const ABLATIONS = [
    ['no_recent_counts', -0.042],
    ['no_spatial_lags', -0.017],
    ['no_calls_for_service', -0.009],
    ['no_calendar', -0.004],
    ['no_fire_911', -0.003],
    ['no_weather', -0.0008],
    ['no_census_context', 0.0006],
  ];
  const PRECINCTS = ['North', 'East', 'South', 'Southwest', 'West'];
  const PRECINCT_SHIFT = { North: -0.01, East: 0.015, South: -0.004, Southwest: -0.03, West: 0.035 };

  for (const m of MODELS) {
    for (const c of CATEGORIES) {
      for (const h of HORIZONS) {
        const row = metricRow(m.id, c.id, h);
        backtestRows.push(row);
        // Historical replay (simulated as-of) covers the 8 weeks before live issuance began;
        // live forecasts started LIVE_DAYS ago, so all live scores are still provisional.
        for (const [source, maturity, n] of [
          ['replay', 'mature', 26 * 24],
          ['replay', 'provisional', (30 - LIVE_DAYS) * 24],
          ['live', 'provisional', (LIVE_DAYS - 3) * 24],
        ]) {
          const pr = metricRow(m.id, c.id, h, (source === 'live' ? -0.018 : -0.01) + jitter(0.006));
          delete pr.ci;
          prospectiveRows.push({ ...pr, maturity, n_forecasts: n, source });
        }
        for (let d = 0; d < 56; d++) {
          const t = PROSPECTIVE_START + d * DAY;
          // live scores only exist once SPD has published the window (~2.5 days)
          if (t + h * HOUR > ANCHOR - 60 * HOUR) continue;
          const source = t >= LIVE_START ? 'live' : 'replay';
          const noise = 0.05 / Math.sqrt(h);
          timeseries.push({
            issued_at: iso(t),
            model_id: m.id,
            category: c.id,
            horizon_h: h,
            capture_10: dec(Math.min(0.95, Math.max(0.02, row.capture_10 - (source === 'live' ? 0.018 : 0.01) + jitter(noise) + 0.015 * Math.sin(d / 5))), 3),
            maturity: ANCHOR - t > MATURITY_DAYS * DAY ? 'mature' : 'provisional',
            source,
          });
        }
        if (m.id === 'lgbm') {
          for (const [name, delta] of ABLATIONS) {
            const dd = delta * (0.8 + 0.4 * r()) * (h === 1 ? 0.7 : 1);
            ablations.push({ name, model_id: m.id, category: c.id, horizon_h: h, capture_10: dec(row.capture_10 + dd, 3), delta_vs_full: dec(dd, 4) });
          }
        }
        // reliability bins on P(>=1)
        const pm = Math.min(0.6, P_MEAN[h] * catScale[c.id]);
        const bins = [];
        for (let b = 0; b < 10; b++) {
          const pMean = Math.min(0.97, pm * Math.pow(10, (b - 5) * 0.22));
          const bias = m.id === 'lgbm' ? 1 + jitter(0.04) : 1 - 0.18 * (b / 9) + jitter(0.04);
          bins.push({
            p_mean: dec(pMean, 4),
            obs_rate: dec(Math.min(0.99, pMean * bias), 4),
            n: Math.round(cells.length * 8760 * 0.5 * Math.pow(0.62, b) * (h === 24 ? 1 / 24 : 1 / h)),
          });
        }
        calibration.push({ model_id: m.id, category: c.id, horizon_h: h, bins });
        for (const p of PRECINCTS) {
          byPrecinct.push({
            model_id: m.id, category: c.id, horizon_h: h, precinct: p,
            capture_10: dec(row.capture_10 + PRECINCT_SHIFT[p] + jitter(0.006), 3),
            n_events: Math.round(CITY_RATE[c.id] * 8760 * (0.14 + 0.1 * r())),
          });
        }
        for (let mo = 0; mo < 12; mo++) {
          const y = 2025 + Math.floor((6 + mo) / 12);
          const month = `${y}-${String(((6 + mo) % 12) + 1).padStart(2, '0')}`;
          byMonth.push({
            model_id: m.id, category: c.id, horizon_h: h, month,
            capture_10: dec(row.capture_10 + 0.012 * Math.sin(mo / 1.9) + jitter(0.007), 3),
            n_events: Math.round(CITY_RATE[c.id] * 730 * (0.9 + 0.2 * r())),
          });
        }
      }
    }
  }

  write('evaluation/summary.json', {
    provenance: PROVENANCE,
    backtest: { test_window: { start: '2025-07-01T07:00:00Z', end: '2026-07-01T07:00:00Z' }, rows: backtestRows },
    prospective: { rows: prospectiveRows, timeseries },
    ablations,
    calibration,
    stability: { by_precinct: byPrecinct, by_month: byMonth },
  }, false);
}

