// Observed "truth": hourly counts per cell for 24h after t, independent of model.
const observedCache = new Map();
function observedHourly(cat, t) {
  const key = `${cat}|${t}`;
  if (observedCache.has(key)) return observedCache.get(key);
  const r = rng(`observed|${key}`);
  const counts = cells.map((cell, i) => {
    const noise = Math.exp(0.35 * normal(r) - 0.06);
    const arr = new Array(24);
    for (let k = 0; k < 24; k++) {
      const tk = t + k * HOUR;
      const mu = baseRate[cat][i] * PROFILE[cat][howOf(tk)] * anomaly(cell, tk, cat) * noise;
      arr[k] = poisson(r, mu);
    }
    return arr;
  });
  observedCache.set(key, counts);
  return counts;
}

function captureAt(expected, observed, frac) {
  const total = observed.reduce((a, b) => a + b, 0);
  if (total === 0) return null;
  const order = expected.map((v, i) => [v, i]).sort((a, b) => b[0] - a[0]);
  const k = Math.max(1, Math.round(frac * expected.length));
  let hit = 0;
  for (let j = 0; j < k; j++) hit += observed[order[j][1]];
  return dec(hit / total, 3);
}

function makeForecast(model, cat, t, status) {
  const forecastId = `fc_${idStamp(t)}_${model}_${cat}`;
  const horizons = {};
  const raw = {};
  for (const h of HORIZONS) {
    const out = {};
    let total = 0;
    const exp = [];
    const pAny = [];
    cells.forEach((cell, i) => {
      const { mu, base } = expectedFor(model, cat, i, t, h);
      total += mu;
      const p = model === 'lgbm' ? 1 - Math.pow(1 + mu / 3, -3) : 1 - Math.exp(-mu);
      const rr = base > 0 ? mu / base : null;
      const lo = model === 'lgbm' ? poissonQuantile(mu * 0.8, 0.05) : null;
      const hi = model === 'lgbm' ? poissonQuantile(mu * 1.35, 0.95) : null;
      out[cell.id] = [sig(mu), sig(p), rr === null ? null : dec(rr, 2), lo, hi];
      exp.push(mu);
      pAny.push(p);
    });
    horizons[String(h)] = {
      window_start: iso(t),
      window_end: iso(t + h * HOUR),
      total_expected: dec(total, 2),
      cells: out,
    };
    raw[h] = { exp, pAny, total };
  }

  let score = null;
  if (status === 'scored_provisional' || status === 'scored_mature') {
    const hourly = observedHourly(cat, t);
    const perHorizon = {};
    const observed = {};
    for (const h of HORIZONS) {
      const obs = hourly.map((arr) => arr.slice(0, h).reduce((a, b) => a + b, 0));
      const obsMap = {};
      obs.forEach((v, i) => {
        if (v > 0) obsMap[cells[i].id] = v;
      });
      const brier = raw[h].pAny.reduce((acc, p, i) => acc + (p - (obs[i] > 0 ? 1 : 0)) ** 2, 0) / cells.length;
      const c10 = captureAt(raw[h].exp, obs, 0.1);
      perHorizon[String(h)] = {
        observed_total: obs.reduce((a, b) => a + b, 0),
        expected_total: dec(raw[h].total, 2),
        capture_at_5pct: captureAt(raw[h].exp, obs, 0.05),
        capture_at_10pct: c10,
        capture_at_20pct: captureAt(raw[h].exp, obs, 0.2),
        pai_at_10pct: c10 === null ? null : dec(c10 / 0.1, 2),
        brier: dec(brier, 4),
        n_cells: cells.length,
      };
      observed[String(h)] = obsMap;
    }
    const mature = status === 'scored_mature';
    score = {
      maturity: mature ? 'mature' : 'provisional',
      scored_at: iso(mature ? t + (MATURITY_DAYS + 1) * DAY : ANCHOR - 30 * 60e3),
      per_horizon: perHorizon,
      observed,
    };
  }

  const modelMeta = MODELS.find((m) => m.id === model);
  return {
    provenance: PROVENANCE,
    forecast_id: forecastId,
    issued_at: iso(t),
    model_id: model,
    model_version: modelMeta.version,
    category: cat,
    data_versions: dataVersions(t),
    feature_cutoffs: featureCutoffs(t),
    columns: ['expected', 'p_any', 'relative_risk', 'lo90', 'hi90'],
    horizons,
    score,
  };
}

// Which forecasts exist (latest for every model × category + 24 past ones).
function statusFor(t) {
  const ageH = (ANCHOR - t) / HOUR;
  if (ageH < 24) return 'frozen'; // 24h window still open
  if (ageH < 60) return 'awaiting_data'; // window over, SPD has not published it yet
  if (ageH > MATURITY_DAYS * 24 + 24) return 'scored_mature';
  return 'scored_provisional';
}
