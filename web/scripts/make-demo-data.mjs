function iso(ms) {
  return new Date(ms).toISOString().replace('.000Z', 'Z');
}
function idStamp(ms) {
  return iso(ms).replace(/[-:]/g, '').replace(/T(\d{4})\d{2}Z$/, 'T$1Z');
}
function compactStamp(ms) {
  return iso(ms).replace(/[-:]/g, '');
}
function hashStr(s) {
  let h = 2166136261 >>> 0;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619) >>> 0;
  }
  return h >>> 0;
}
function rng(seedStr) {
  let a = hashStr(seedStr) || 1;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
function normal(r) {
  const u = Math.max(r(), 1e-12);
  const v = r();
  return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * v);
}
function poisson(r, mu) {
  if (mu <= 0) return 0;
  if (mu > 40) return Math.max(0, Math.round(mu + Math.sqrt(mu) * normal(r)));
  const L = Math.exp(-mu);
  let k = 0;
  let p = 1;
  do {
    k++;
    p *= r();
  } while (p > L);
  return k - 1;
}
function poissonQuantile(mu, q) {
  let k = 0;
  let pk = Math.exp(-mu);
  let cdf = pk;
  while (cdf < q && k < 1000) {
    k++;
    pk *= mu / k;
    cdf += pk;
  }
  return k;
}
const sig = (x, n = 2) => (x === 0 ? 0 : Number(x.toPrecision(n)));
const dec = (x, n = 2) => Number(x.toFixed(n));

function pointInPolygon([x, y], poly) {
  let inside = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i];
    const [xj, yj] = poly[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

const LAT0 = (BBOX[1] + BBOX[3]) / 2;
const PHI = (LAT0 * Math.PI) / 180;
const M_PER_DEG_LAT = 111132.954 - 559.822 * Math.cos(2 * PHI) + 1.175 * Math.cos(4 * PHI);
const M_PER_DEG_LON = 111412.84 * Math.cos(PHI) - 93.5 * Math.cos(3 * PHI);
const D_LAT = CELL_M / M_PER_DEG_LAT;
const D_LON = CELL_M / M_PER_DEG_LON;

function kmBetween(lon1, lat1, lon2, lat2) {
  const dx = ((lon1 - lon2) * M_PER_DEG_LON) / 1000;
  const dy = ((lat1 - lat2) * M_PER_DEG_LAT) / 1000;
  return Math.hypot(dx, dy);
}
function kmToSegment(lon, lat, [x1, y1, x2, y2]) {
  const px = lon * M_PER_DEG_LON;
  const py = lat * M_PER_DEG_LAT;
  const ax = x1 * M_PER_DEG_LON;
  const ay = y1 * M_PER_DEG_LAT;
  const bx = x2 * M_PER_DEG_LON;
  const by = y2 * M_PER_DEG_LAT;
  const t = Math.max(0, Math.min(1, ((px - ax) * (bx - ax) + (py - ay) * (by - ay)) / ((bx - ax) ** 2 + (by - ay) ** 2)));
  return Math.hypot(px - (ax + t * (bx - ax)), py - (ay + t * (by - ay))) / 1000;
}

