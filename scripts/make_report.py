#!/usr/bin/env python
"""Render reports/backtest_results.md (+ a compact JSON) from executed backtests.

    python scripts/make_report.py

Only numbers present in artifacts/backtests/**/report.json are reported.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from seacrime.config import load_config  # noqa: E402

ORDER = ["hotspot", "seasonal", "poisson_glm", "negbin_glm", "lgbm", "lgbm_resid", "catboost", "tcn", "convlstm", "stgnn", "transformer", "hawkes"]


def pct(x, d=1):
    return "–" if x is None else f"{100 * x:.{d}f}%"


def num(x, d=4):
    return "–" if x is None else f"{x:.{d}f}"


def ci(r, k):
    c = r.get("ci90", {}).get(k)
    return "" if not c else f" [{100 * c[0]:.1f}, {100 * c[1]:.1f}]"


def load_reports(root: Path) -> dict[str, dict]:
    out = {}
    for d in sorted(root.iterdir()) if root.exists() else []:
        latest = d / "LATEST"
        if latest.exists():
            p = d / latest.read_text().strip() / "report.json"
            if p.exists():
                out[d.name] = json.loads(p.read_text())
        elif (d / "report.json").exists():
            out[d.name] = json.loads((d / "report.json").read_text())
    return out


def model_table(rep: dict) -> list[str]:
    L = ["| h | model | capture@5% | capture@10% [90% CI] | capture@20% | PAI@10 | Δcap@10 vs seasonal [90% CI] | hit@top-25 cells | Poisson dev. | NB NLL | Brier | ECE | pred/obs |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for h, hr in sorted(rep["horizons"].items(), key=lambda x: int(x[0])):
        ms = hr["models"]
        best_dev = min(r["poisson_deviance"] for r in ms.values())
        best_cap = max(r["capture_10"] for r in ms.values())
        for m in sorted(ms, key=lambda x: ORDER.index(x) if x in ORDER else 99):
            r = ms[m]
            dlt = r.get("delta_capture_10_vs_seasonal")
            dtxt = "–" if not dlt else f"{100 * dlt['delta']:+.2f} pp [{100 * dlt['ci90'][0]:+.2f}, {100 * dlt['ci90'][1]:+.2f}]"
            cap10 = pct(r["capture_10"]) + ci(r, "capture_10")
            if r["capture_10"] == best_cap:
                cap10 = f"**{cap10}**"
            dev = num(r["poisson_deviance"], 5)
            if r["poisson_deviance"] == best_dev:
                dev = f"**{dev}**"
            L.append(f"| {h} | {m} | {pct(r['capture_5'])} | {cap10} | {pct(r['capture_20'])} | {num(r['pai_10'], 2)} | {dtxt} | {pct(r.get('hit_top25'))} | {dev} | {num(r['nll'], 5)} | {num(r['brier'], 5)} | {num(r['ece'], 5)} | {num(r['calibration_in_large'], 3)} |")
    return L


def main() -> None:
    cfg = load_config()
    reps = load_reports(cfg.artifacts_root / "backtests")
    L = ["# Backtest results", "", "Generated by `python scripts/make_report.py` from the executed runs in `artifacts/backtests/`. "
         "Every model in a table was scored on the identical hourly issue times × forecast cells. Capture@k% = share of reported incidents in the k% of cells ranked highest; "
         "Δ vs seasonal uses a paired day-block bootstrap. Lower is better for deviance/NLL/Brier/ECE; pred/obs is calibration-in-the-large (1 = unbiased).", ""]
    compact = {}
    rank = {"property_report": 0, "property_report_resid": 1, "violent_report": 2, "all_located_report": 3, "property_offense": 4, "property_report_ablation": 5}
    reps = dict(sorted(reps.items(), key=lambda kv: (rank.get(kv[0], 6), kv[0])))
    for name, rep in reps.items():
        if name.endswith("_rolling"):
            continue
        tag = rep.get("tag", "")
        if tag.startswith("fold"):
            continue
        sp = rep["split"]
        L += [f"## {rep['category']} · event time = {rep['event_time']}" + (f" · run `{tag}`" if tag else ""), "",
              f"Run `{rep['run_id']}`; train issue times from {sp['train_start'][:10]} (n={rep.get('n_train_issue_times')}), validation from {sp['val_start'][:10]}, "
              f"**test {sp['test_start'][:10]} → {sp['test_end'][:10]}** (mature), provisional {sp['test_end'][:10]} → {sp['data_end'][:16]}; "
              f"{rep['n_active_cells']} cells; crime availability lag {rep['crime_lag_h']} h; test stride {rep.get('test_stride_h', 1)} h; data versions {rep['data_versions'].get('spd_crime')}.", ""]
        if any(hr["models"] for hr in rep["horizons"].values()):
            L += model_table(rep) + [""]
        prov = [(h, m, r) for h, hr in rep["horizons"].items() for m, r in hr.get("provisional", {}).items()]
        if prov:
            L += ["Provisional window (reports still arriving; not comparable to mature numbers):", "",
                  "| h | model | capture@10% | Poisson dev. | observed |", "|---|---|---|---|---|"]
            L += [f"| {h} | {m} | {pct(r['capture_10'])} | {num(r['poisson_deviance'], 5)} | {int(r['observed_total'])} |" for h, m, r in sorted(prov, key=lambda x: (int(x[0]), x[1]))]
            L.append("")
        abl = [(h, a, r) for h, hr in rep["horizons"].items() for a, r in hr.get("ablations", {}).items()]
        if abl:
            L += ["### Ablations (LightGBM retrained without a feature group)", "",
                  "| h | removed | capture@10% | Δcap@10 (full − ablated) [90% CI] | Δ deviance (full − ablated) | event-window capture@10% |", "|---|---|---|---|---|---|"]
            for h, a, r in sorted(abl, key=lambda x: (int(x[0]), x[1])):
                d = r["delta_capture_10_full_minus_ablated"]
                ev = r.get("event_windows") or {}
                L.append(f"| {h} | {a} | {pct(r['capture_10'])} | {100 * d['delta']:+.2f} pp [{100 * d['ci90'][0]:+.2f}, {100 * d['ci90'][1]:+.2f}] | {r['delta_deviance_full_minus_ablated']:+.6f} | {pct(ev.get('capture_10'))} |")
            L.append("")
        ev_rows = [(h, m, r.get("_event_windows")) for h, hr in rep["horizons"].items() for m, r in hr["models"].items() if r.get("_event_windows")]
        if ev_rows:
            L += ["### Windows overlapping major events (sports / ≥10k permits)", "", "| h | model | issue times | capture@10% | Poisson dev. | pred/obs |", "|---|---|---|---|---|---|"]
            L += [f"| {h} | {m} | {e['n_issue_times']} | {pct(e['capture_10'])} | {num(e['poisson_deviance'], 5)} | {num(e['calibration_in_large'], 3)} |" for h, m, e in sorted(ev_rows, key=lambda x: (int(x[0]), x[1]))]
            L.append("")
        if rep.get("lag_sensitivity"):
            L += ["### Crime-data availability lag sensitivity (h = 24, LightGBM re-trained per lag; test stride 6 h; seasonal shown with untuned defaults κ=26, σ=1)", "",
                  "| lag (h) | LightGBM capture@10% | seasonal capture@10% | LightGBM deviance | seasonal deviance |", "|---|---|---|---|---|"]
            for lag, r in sorted(rep["lag_sensitivity"].items(), key=lambda x: int(x[0])):
                L.append(f"| {lag} | {pct(r['lgbm_capture_10'])} | {pct(r['seasonal_capture_10'])} | {num(r['lgbm_deviance'], 5)} | {num(r['seasonal_deviance'], 5)} |")
            L.append("")
        for h, hr in sorted(rep["horizons"].items(), key=lambda x: -int(x[0])):
            lg = hr["models"].get("lgbm")
            if lg and lg.get("_precinct"):
                L += [f"### Geographic stability (h = {h}, LightGBM)", "", "| precinct | observed (summed over overlapping windows) | pred/obs | capture@10% within precinct | deviance |", "|---|---|---|---|---|"]
                L += [f"| {p} | {int(d['obs'])} | {num(d['calib'], 3) if d['obs'] > 0 else '–'} | {pct(d['capture_10_within']) if d['obs'] > 0 else '–'} | {num(d['deviance'], 5)} |"
                      for p, d in sorted(lg["_precinct"].items())]
                L.append("")
                break
        compact[name] = {h: {m: {k: r.get(k) for k in ("capture_5", "capture_10", "capture_20", "poisson_deviance", "nll", "brier", "ece", "calibration_in_large", "ci90")}
                             for m, r in hr["models"].items()} for h, hr in rep["horizons"].items()}
    for name, rep in reps.items():
        if not name.endswith("_rolling"):
            continue
        L += [f"## Rolling-origin backtest · {rep['category']} ({rep['protocol']})", "",
              f"Origins {', '.join(rep['origins'])}; each fold retrains on all data available at its origin and is tested on the next {rep['fold_days']} days.", "",
              "| h | model | pooled capture@10% [90% CI] | Δ vs seasonal [90% CI] | Poisson dev. | pred/obs |", "|---|---|---|---|---|---|"]
        for h, pr in sorted(rep["pooled"].items(), key=lambda x: int(x[0])):
            for m, r in sorted(pr.items(), key=lambda x: ORDER.index(x[0]) if x[0] in ORDER else 99):
                d = r.get("delta_capture_10_vs_seasonal")
                dt = "–" if not d else f"{100 * d['delta']:+.2f} pp [{100 * d['ci90'][0]:+.2f}, {100 * d['ci90'][1]:+.2f}]"
                L.append(f"| {h} | {m} | {pct(r['capture_10'])}{ci(r, 'capture_10')} | {dt} | {num(r['poisson_deviance'], 5)} | {num(r['calibration_in_large'], 3)} |")
        L += ["", "Per fold:", "", "| fold test window | h | model | capture@10% | pred/obs |", "|---|---|---|---|---|"]
        for f in rep["folds"]:
            for h, ms in f["horizons"].items():
                for m, r in ms.items():
                    L.append(f"| {f['test_start'][:10]} → {f['test_end'][:10]} | {h} | {m} | {pct(r['capture_10'])} | {num(r['calibration_in_large'], 3)} |")
        L.append("")
        compact[name] = rep["pooled"]
    out = ROOT / "reports"
    runs = out / "runs"
    runs.mkdir(exist_ok=True)
    for name, rep in reps.items():  # preserve raw run reports (small JSON) in git
        (runs / f"{name}.json").write_text(json.dumps(rep, indent=1, default=str))
    (out / "backtest_results.md").write_text("\n".join(L) + "\n")
    (out / "backtest_results.json").write_text(json.dumps(compact, indent=1, default=str))
    print("\n".join(L)[:6000])


if __name__ == "__main__":
    main()
